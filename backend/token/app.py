"""FastAPI app: /healthz, /token, and static serving of the built frontend.

Run it with:  uvicorn backend.token.app:app --port 7860
"""

from pathlib import Path
import secrets

from fastapi import FastAPI, HTTPException, Request
from fastapi.staticfiles import StaticFiles
from livekit import api
from pydantic import BaseModel

from . import config, security
from .ratelimit import throttle

app = FastAPI(title="livekit-voice-agent token server")
security.install(app)


class TokenRequest(BaseModel):
    identity: str | None = None
    room: str | None = None
    password: str | None = None


class TokenResponse(BaseModel):
    url: str
    token: str
    room: str
    identity: str
    avatar: bool


@app.get("/healthz")
def healthz() -> dict:
    return {"ok": True, "avatar": config.AVATAR_ENABLED}


@app.post("/token", response_model=TokenResponse)
def create_token(req: TokenRequest, request: Request) -> TokenResponse:
    if not (config.LIVEKIT_URL and config.LIVEKIT_API_KEY and config.LIVEKIT_API_SECRET):
        raise HTTPException(
            status_code=500,
            detail="LIVEKIT_URL, LIVEKIT_API_KEY and LIVEKIT_API_SECRET must be set",
        )

    throttle(request)

    if not config.APP_PASSWORD:
        raise HTTPException(
            status_code=500,
            detail="APP_PASSWORD is not configured on the server",
        )

    supplied = (req.password or "").encode("utf-8")
    if not secrets.compare_digest(supplied, config.APP_PASSWORD.encode("utf-8")):
        raise HTTPException(status_code=401, detail="invalid password")

    if req.room is not None or req.identity is not None:
        raise HTTPException(
            status_code=400, detail="room and identity are generated by the server"
        )

    room = f"room-{secrets.token_hex(4)}"
    identity = f"user-{secrets.token_hex(4)}"

    if not config.NAME_RE.match(room) or not config.NAME_RE.match(identity):
        raise HTTPException(status_code=400, detail="invalid room or identity")

    token = (
        api.AccessToken(config.LIVEKIT_API_KEY, config.LIVEKIT_API_SECRET)
        .with_identity(identity)
        .with_name(identity)
        .with_ttl(config.TOKEN_TTL)
        .with_grants(
            api.VideoGrants(
                room_join=True,
                room=room,
                can_publish=True,
                can_subscribe=True,
                can_publish_data=True,
            )
        )
        .to_jwt()
    )

    return TokenResponse(
        url=config.LIVEKIT_URL,
        token=token,
        room=room,
        identity=identity,
        avatar=config.AVATAR_ENABLED,
    )


# serve the production build of the frontend on the same origin when it exists,
# which keeps the token endpoint out of CORS territory
_dist = Path(__file__).resolve().parents[2] / "frontend" / "dist"
if _dist.is_dir():
    app.mount("/", StaticFiles(directory=_dist, html=True), name="frontend")
